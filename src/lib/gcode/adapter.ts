import { invoke } from "@tauri-apps/api/core";
import type { MachineProfile } from "#lib/bindings/MachineProfile.js";
import type { JobPlacement } from "#lib/bindings/gcode/JobPlacement.js";
import type { JobSummary } from "#lib/bindings/gcode/JobSummary.js";
import type { DesignDocument } from "#lib/bindings/project/DesignDocument.js";
import { desktop } from "#lib/desktop/platform.js";

/** What GCode is generated from. */
export interface GcodeRequest {
  document: DesignDocument;
  /** The active machine profile; GRBL defaults when there is none yet. */
  profile: MachineProfile | null;
  placement: JobPlacement;
}

/** Typed access to the GCode commands in `src-tauri/src/gcode.rs`. */
export interface GcodeAdapter {
  /** False in the browser preview, which has no GCode generator. */
  readonly available: boolean;
  /** What the job would do: bounds, bed check, size. */
  summary(request: GcodeRequest): Promise<JobSummary>;
  /** Asks where to save `<name>.gcode` and writes it. The path, or null if cancelled. */
  export(request: GcodeRequest, name: string): Promise<string | null>;
}

export const desktopGcode: GcodeAdapter = {
  available: true,
  summary: (request) => invoke<JobSummary>("gcode_summary", { ...request }),
  export: (request, name) => invoke<string | null>("gcode_export", { ...request, name }),
};

export const PREVIEW_NO_GCODE =
  "Browser preview: GCode is generated by the desktop app (npm run desktop:dev).";

// The browser preview has no Rust side, so it can't plan or write GCode.
export const previewGcode: GcodeAdapter = {
  available: false,
  summary: async () => {
    throw new Error(PREVIEW_NO_GCODE);
  },
  export: async () => {
    throw new Error(PREVIEW_NO_GCODE);
  },
};

export const gcodeAdapter = desktop ? desktopGcode : previewGcode;
